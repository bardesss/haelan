// Writes TOOLS.md from the tool catalogue that ships: the same names, descriptions and Zod shapes
// the server hands an MCP client in `tools/list`. A hand written TOOLS.md would be a second source
// of truth, and would drift the first time a description was tuned rather than the file. This
// script is the only thing that writes TOOLS.md; `apps/server/test/tools-doc-drift.test.ts` calls
// the same `render` this file exports and fails the suite when the checked-in file disagrees with
// it, which is what keeps the two from drifting apart unnoticed.
//
// Usage: pnpm docs:tools
import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { CATALOGUE } from '../apps/server/src/mcp/catalogue.ts'
import { DEFAULT_DAILY_POINTS, DEFAULT_INTRADAY_POINTS, MAX_POINTS } from '../apps/server/src/mcp/contract.ts'

/**
 * Peels every `optional`/`nullable` wrapper off a Zod schema and reports what was under them: the
 * unwrapped base schema, whether either wrapper was present, and the first `.describe()` text found
 * at any layer — `.describe()` attaches to whichever schema instance it was called on, which is not
 * always the outermost one (an inline field describes its base type; `points` on get_workouts
 * describes the `.optional()` wrapper), so every layer is checked rather than only the first.
 */
function unwrap(schema) {
  let optional = false
  let nullable = false
  let description = schema.description
  let s = schema
  while (s.def.type === 'optional' || s.def.type === 'nullable') {
    if (s.def.type === 'optional') optional = true
    else nullable = true
    s = s.def.innerType
    if (description === undefined) description = s.description
  }
  return { base: s, optional, nullable, description }
}

/** A one-line label for an unwrapped (no optional/nullable) schema. */
function label(base) {
  const def = base.def
  if (def.type === 'enum') return Object.keys(def.entries).map((k) => `'${k}'`).join(' | ')
  if (def.type === 'array') {
    const element = unwrap(def.element)
    return element.base.def.type === 'object' ? 'array of object' : `array of ${label(element.base)}`
  }
  return def.type // 'string', 'number', 'boolean', 'object', or whatever Zod calls a type we have not named
}

/**
 * One field as a Markdown bullet, followed by its children indented one level when the field is an
 * object or an array of objects — a workout's `trace` is an array of objects carrying an array of
 * objects, and a flat list would either lose that shape or flatten it into one unreadable line.
 */
function renderField(name, schema, depth, lines) {
  const { base, optional, nullable, description } = unwrap(schema)
  const flags = [nullable ? 'nullable' : null, optional ? 'optional' : null].filter((f) => f !== null)
  const meta = flags.length > 0 ? `${label(base)}, ${flags.join(', ')}` : label(base)
  const suffix = description !== undefined ? ` — ${description}` : ''
  lines.push(`${'  '.repeat(depth)}- **${name}** (${meta})${suffix}`)

  if (base.def.type === 'object') {
    for (const [childName, childSchema] of Object.entries(base.def.shape)) {
      renderField(childName, childSchema, depth + 1, lines)
    }
  } else if (base.def.type === 'array') {
    const element = unwrap(base.def.element)
    if (element.base.def.type === 'object') {
      for (const [childName, childSchema] of Object.entries(element.base.def.shape)) {
        renderField(childName, childSchema, depth + 1, lines)
      }
    }
  }
}

/** A Zod raw shape (a `Tool`'s `inputSchema` or `outputSchema`) as Markdown bullets, oldest key first. */
function renderShape(shape) {
  const entries = Object.entries(shape)
  if (entries.length === 0) return ['None.']
  const lines = []
  for (const [name, schema] of entries) renderField(name, schema, 0, lines)
  return lines
}

/**
 * The whole file, as a string. Exported so the drift test can call it directly rather than
 * spawning this script and reading back what it wrote — the same question, asked more cheaply and
 * without a temp file to clean up.
 */
export function render() {
  const lines = [
    '# Tool Reference',
    '',
    'Generated by `pnpm docs:tools` from `apps/server/src/mcp/catalogue.ts` — the same names, '
      + 'descriptions and schemas the server hands an MCP client in `tools/list`. Do not hand edit '
      + 'this file: `apps/server/test/tools-doc-drift.test.ts` regenerates it into a string and '
      + 'fails the suite when it disagrees with what is checked in here. Change a tool, run `pnpm '
      + 'docs:tools`, and commit the result.',
    '',
    '## Budgets',
    '',
    'Every tool that returns a series answers at most a few hundred points: '
      + `${DEFAULT_DAILY_POINTS} by default for a daily series, ${DEFAULT_INTRADAY_POINTS} for an `
      + `intraday or workout trace, and never more than ${MAX_POINTS} regardless of what \`points\` `
      + 'asks for. The budget is the server\'s to set, not the caller\'s to request: an agent does '
      + 'not know its own context window, and one asked to pick a number picks a generous one. A '
      + 'thinned answer says so in `reduction`, and `summary` carries the true extremes the thinned '
      + 'points might otherwise hide.',
    '',
    '## Running it',
    '',
    '```',
    'docker exec -i haelan node --experimental-strip-types apps/server/src/mcp.ts --person <name>',
    '```',
    '',
    '`--person` is a binding, not a permission check. It says which person in the household this '
      + 'process answers for; it does not gate who is allowed to run the command. A process that can '
      + '`docker exec` into the container can already read the whole database file underneath it, '
      + '`--person` or no `--person` — so the ability to reach the container is the real security '
      + 'boundary, and this flag is not a second one. Do not treat it as access control.',
    '',
    '## Where the data goes',
    '',
    'Pointing an LLM at this server sends that person\'s health data to whichever model provider is '
      + 'on the other end of the conversation. Self-hosting the store does not self-host the model: '
      + 'haelan keeps the database on your own disk, but the moment an agent calls one of these '
      + 'tools, the answer it reads leaves the house for wherever that model runs.',
    '',
    `## Tools (${CATALOGUE.length})`,
  ]

  for (const tool of CATALOGUE) {
    lines.push('', `### ${tool.name}`, '', tool.description)
    if (tool.notes !== undefined) lines.push('', tool.notes)
    lines.push('', '**Input**', '', ...renderShape(tool.inputSchema))
    lines.push('', '**Output**', '', ...renderShape(tool.outputSchema))
  }

  lines.push('')
  return lines.join('\n')
}

if (import.meta.main) {
  const target = new URL('../TOOLS.md', import.meta.url)
  await writeFile(target, render())
  console.error(`docs:tools: wrote ${CATALOGUE.length} tools to ${fileURLToPath(target)}`)
}
